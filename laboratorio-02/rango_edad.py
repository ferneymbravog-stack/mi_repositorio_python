
nota = float(input("Nota: "))

if 0.0 <= nota <= 5.0:
    print("Nota dentro del rango.")
else:
    print("La nota está fuera del rango permitido.")

edad = int(input("Edad: "))

if 18 <= edad <= 65:
    print("La edad está dentro del rango permitido (18 a 65).")
else:
    print("La edad está fuera del rango permitido (18 a 65).")

